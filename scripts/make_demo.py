def main(recorded: Path) -> None:
    files = ["state.json", "campaign.json", "last_plan.json", "companies/anthropic.json"]
    for f in files:
        if not (recorded / f).exists():
            sys.exit(f"Missing {recorded / f}")

    # day1: the recorded run, verbatim.
    day1 = DEMO / "day1"
    shutil.rmtree(day1, ignore_errors=True)
    for f in files:
        (day1 / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(recorded / f, day1 / f)
    plan_date = json.loads((recorded / "last_plan.json").read_text())["date"]
    (day1 / "demo.json").write_text(json.dumps({"today": plan_date, "label": "Day one (recorded run)"}, indent=2))

    # midway: same intel + campaign, simulated history and a plan for MIDWAY_TODAY.
    mid = DEMO / "midway"
    shutil.rmtree(mid, ignore_errors=True)
    for f in ("campaign.json", "companies/anthropic.json"):
        (mid / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(recorded / f, mid / f)
    store = Store(mid / "state.json")
    src = Store(recorded / "state.json").load()
    src.records = {}
    for d, title, topic, outcome, minutes, note in HISTORY:
        rec = src.record_for(title, topic)
        attempt = Attempt(
            date=d, minutes=minutes, outcome=outcome,
            used_hint=outcome == "solved_with_hints",
            viewed_solution=outcome == "viewed_solution", notes=note,
        )
        review.apply_attempt(rec, attempt, date.fromisoformat(d))
    store.save(src)
    (mid / "last_plan.json").write_text(json.dumps(MIDWAY_PLAN, indent=2))
    (mid / "demo.json").write_text(json.dumps({"today": MIDWAY_TODAY, "label": "Midway (simulated history)"}, indent=2))

    due = [t for t, r in src.records.items() if review.is_due(r, date.fromisoformat(MIDWAY_TODAY))]
    print(f"Wrote {day1} and {mid}. Due on {MIDWAY_TODAY}: {due}")


if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/lc_live"))
